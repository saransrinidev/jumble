const {chromium}=require('playwright')
const {pathToFileURL}=require('node:url')
const path=require('node:path')
const fs=require('node:fs')
const assert=require('node:assert/strict')
;(async()=>{
 const browser=await chromium.launch({headless:true})
 try{
 const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'})
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 const url=pathToFileURL(path.resolve(__dirname,'../../designs/jumble-design.html')).href
 await page.goto(url+'#dashboard')
 await page.getByRole('link',{name:'Create Game',exact:true}).click()
 await page.getByRole('heading',{name:'Create your game.'}).waitFor()
 await page.getByLabel('Game title').fill('Two-round custom game')
 assert.equal(await page.locator('.selected-rounds>span').count(),4)
 await page.getByRole('button',{name:'Remove Memory Grid',exact:true}).click()
 await page.getByRole('button',{name:'Remove Emoji Decode',exact:true}).click()
 await page.getByRole('button',{name:'Remove Draw & Guess',exact:true}).click()
 assert.equal(await page.locator('.selected-rounds>span').count(),1)
 await page.getByRole('button',{name:'Add round',exact:true}).click()
 await page.getByLabel('Round name',{exact:true}).fill('Movie Trivia')
 await page.getByLabel('Round type',{exact:true}).selectOption('quiz')
 await page.getByRole('button',{name:'Add round',exact:true}).last().click()
 assert.equal(await page.locator('.selected-rounds>span').count(),2)
 await page.getByRole('button',{name:'Add question',exact:true}).click()
 await page.getByLabel('Question',{exact:true}).fill('Which movie has Simba?')
 await page.getByLabel('Accepted answer').fill('The Lion King')
 await page.getByRole('button',{name:'Save Game',exact:true}).click()
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('jumble.design.games'))[0].rounds.length),2)
 await page.goto(url+'#settings')
 await page.getByLabel('Color theme',{exact:true}).selectOption('light')
 assert.equal(await page.locator('html').getAttribute('data-theme'),'light')
 const output=path.resolve(__dirname,'../../test-artifacts/jumble-design');fs.mkdirSync(output,{recursive:true})
 for(const route of ['dashboard','host','results','login','create']){
  await page.goto(url+'#'+route)
  await page.screenshot({path:path.join(output,route+'-light.png'),fullPage:true,timeout:60000})
  await page.setViewportSize({width:390,height:844})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,route+' mobile')
  await page.setViewportSize({width:1440,height:1000})
 }
 await page.reload()
 assert.equal(await page.locator('html').getAttribute('data-theme'),'light')
 assert.deepEqual(errors,[])
 console.log('Theme and game options passed: direct create page, configurable rounds, custom quiz, saved round selection, persistent white theme, and mobile layouts.')
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
