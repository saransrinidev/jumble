const {chromium}=require('playwright')
const {spawn}=require('node:child_process')
const path=require('node:path'),fs=require('node:fs'),assert=require('node:assert/strict')
const root=path.resolve(__dirname,'..'),base='http://127.0.0.1:5192',out=path.resolve(root,'../test-artifacts/profile-character')
let server,browser
;(async()=>{
 fs.mkdirSync(out,{recursive:true})
 server=spawn(process.execPath,[path.join(root,'node_modules/vite/bin/vite.js'),'preview','--host','127.0.0.1','--port','5192','--strictPort'],{cwd:root,stdio:['ignore','pipe','pipe']})
 await new Promise((resolve,reject)=>{const timer=setTimeout(()=>reject(Error('Preview timeout')),20000);server.stdout.on('data',d=>{if(d.toString().includes('5192')){clearTimeout(timer);resolve()}});server.on('exit',c=>reject(Error('Preview exited '+c)))})
 browser=await chromium.launch({headless:true})
 const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'}),errors=[]
 page.on('pageerror',e=>errors.push(e.message))
 const login=async id=>{await page.getByLabel('Your user ID').fill(id);await page.getByRole('button',{name:'Enter dashboard'}).click();await page.waitForURL('**/dashboard');await page.getByRole('link',{name:'Profile',exact:true}).click()}
 await page.goto(base+'/login');await login('GIPL042')
 assert.equal(await page.locator('.profile-grid textarea').count(),0)
 assert.equal(await page.locator('.profile-mascot').count(),0)
 for(const field of ['Name','User ID','Current team'])assert.equal(await page.getByLabel(field,{exact:true}).evaluate(el=>el.readOnly),true)
 await page.getByRole('button',{name:'Change character',exact:true}).click()
 await page.getByRole('button',{name:'Cloud Cruiser',exact:true}).click()
 await page.getByRole('button',{name:'Use character',exact:true}).click()
 assert.equal(await page.locator('a[aria-label="Open profile"] img').getAttribute('src'),'/design-assets/cloud.png')
 await page.reload()
 await page.getByRole('heading',{name:'Cloud Cruiser',exact:true}).waitFor()
 await page.screenshot({path:path.join(out,'profile-dark.png'),fullPage:true})
 await page.getByRole('button',{name:'Change character',exact:true}).click()
 await page.getByRole('button',{name:'Royal Knight',exact:true}).click()
 await page.getByRole('button',{name:'Cancel',exact:true}).click()
 assert.equal(await page.locator('a[aria-label="Open profile"] img').getAttribute('src'),'/design-assets/cloud.png')
 await page.getByRole('button',{name:'Switch to light theme',exact:true}).click()
 await page.setViewportSize({width:390,height:844})
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
 await page.screenshot({path:path.join(out,'profile-mobile.png'),fullPage:true})
 await page.getByRole('button',{name:'Change character',exact:true}).click()
 await page.screenshot({path:path.join(out,'picker-mobile.png'),fullPage:true})
 await page.getByRole('button',{name:'Cancel',exact:true}).click()
 await page.setViewportSize({width:1440,height:1000})
 await page.getByRole('button',{name:'Log out',exact:true}).click();await login('GIPL099')
 await page.getByRole('heading',{name:'Jumble Buddy',exact:true}).waitFor()
 await page.getByRole('button',{name:'Log out',exact:true}).click();await login('GIPL042')
 await page.getByRole('heading',{name:'Cloud Cruiser',exact:true}).waitFor()
 assert.deepEqual(errors,[])
 console.log('Profile passed: no About or team mascot, read-only details, character/header sync, saved selection, cancel, separate users, and mobile layout.')
})().catch(e=>{console.error(e);process.exitCode=1}).finally(async()=>{await browser?.close();server?.kill()})
