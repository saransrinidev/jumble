const { chromium } = require('playwright')
const path = require('node:path')
const fs = require('node:fs')
const assert = require('node:assert/strict')
const base = process.env.DESIGN_PREVIEW_URL || 'http://127.0.0.1:5194/'
const output = path.resolve(__dirname, '../../test-artifacts/jumble-design')
let browser
;(async()=>{
  fs.mkdirSync(output,{recursive:true})
  browser=await chromium.launch({headless:true})
  const context=await browser.newContext({viewport:{width:1512,height:1050},reducedMotion:'reduce'})
  const page=await context.newPage(), errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  for(const screen of ['dashboard','lobby','host','results','history','enter','login','games','build','profile','settings']){
    await page.goto(base+'#'+screen)
    await page.locator('#app').waitFor()
    await page.evaluate(()=>document.fonts.ready)
    await page.screenshot({path:path.join(output,screen+'.png'),fullPage:true})
    const missing=await page.locator('#app img').evaluateAll(imgs=>imgs.filter(img=>img.complete&&img.naturalWidth===0).map(img=>img.src))
    assert.deepEqual(missing,[],screen+' broken images')
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,screen+' desktop overflow')
  }
  await page.goto(base+'#login')
  await page.getByLabel('Your user ID').fill('GIPL042')
  await page.getByRole('button',{name:'Enter dashboard'}).click()
  await page.waitForURL(/#dashboard$/)
  await page.getByRole('button',{name:'Host Game',exact:true}).click()
  await page.getByRole('button',{name:'Open host lobby'}).click()
  await page.waitForURL(/#host$/)
  await page.getByRole('button',{name:'Add demo player'}).click()
  await page.getByLabel('Team for Maya Chen').selectOption('2')
  await page.getByRole('link',{name:'Build Game',exact:true}).click()
  await page.getByRole('button',{name:'Add New Game'}).click()
  await page.getByLabel('Game title').fill('Design QA showdown')
  await page.getByRole('button',{name:'Add question',exact:true}).click()
  await page.getByLabel('Question',{exact:true}).fill('What is 2 + 2?')
  await page.getByLabel('Accepted answer').fill('4')
  await page.getByRole('button',{name:'Save Game',exact:true}).click()
  await page.getByText('Design QA showdown',{exact:true}).first().waitFor()
  await page.goto(base+'#history')
  await page.getByRole('button',{name:'Hosted',exact:true}).click()
  assert.equal(await page.locator('.history-card').count(),2)
  await page.getByLabel('Search game history').fill('After Hours')
  assert.equal(await page.locator('.history-card:visible').count(),1)
  await page.goto(base+'#profile')
  await page.getByLabel('Display name').fill('Harsha Player')
  await page.getByRole('button',{name:'Save changes'}).click()
  await page.getByRole('heading',{name:'Hey, Harsha Player.'}).waitFor()
  await page.goto(base+'#settings')
  await page.getByRole('switch',{name:'Reduce motion'}).click()
  assert.equal(await page.getByRole('switch',{name:'Reduce motion'}).getAttribute('aria-checked'),'true')
  await page.setViewportSize({width:390,height:844})
  for(const screen of ['dashboard','lobby','host','results','history','enter','login','build','profile','settings']){
    await page.goto(base+'#'+screen)
    await page.screenshot({path:path.join(output,screen+'-mobile.png'),fullPage:true})
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,screen+' mobile overflow')
  }
  assert.deepEqual(errors,[])
  console.log('HTML design checks passed: 11 desktop screens, 10 mobile screens, login, hosting, team assignment, game creation, history search, profile, and settings.')
})().catch(e=>{console.error(e);process.exitCode=1}).finally(async()=>{await browser?.close()})
