const { chromium } = require('playwright')
const { spawn } = require('node:child_process')
const path = require('node:path')
const fs = require('node:fs')
const assert = require('node:assert/strict')
const root = path.join(__dirname, '..')
const base = 'http://127.0.0.1:5183'
let server, browser
;(async () => {
  server = spawn(process.execPath, [path.join(root, 'node_modules/vite/bin/vite.js'), '--host', '127.0.0.1', '--port', '5183', '--strictPort'], { cwd: root, env: { ...process.env, VITE_STATIC: 'true', VITE_API_URL: '' }, stdio: ['ignore', 'pipe', 'pipe'] })
  await new Promise((resolve, reject) => { const timeout = setTimeout(() => reject(new Error('Server startup timed out')), 20000); server.stdout.on('data', d => { if (d.toString().includes('5183')) { clearTimeout(timeout); resolve() } }); server.on('exit', c => reject(new Error('Server exited ' + c))) })
  browser = await chromium.launch({ headless: true })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' })
  const page = await context.newPage(), errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(base)
  await page.getByLabel('Your user ID').fill('GIPL042')
  await page.getByRole('button', { name: 'Log in', exact: true }).click()
  await page.waitForURL('**/dashboard')
  await page.getByRole('heading', { name: 'Welcome back, GIPL042.' }).waitFor()
  assert.equal(await page.getByRole('button', { name: 'Join Game', exact: true }).count(), 0)
  assert.equal(await page.getByRole('link', { name: 'Build Game' }).count(), 0)
  await page.getByRole('button', { name: 'Host Game', exact: true }).click()
  await page.getByRole('button', { name: 'Open lobby' }).click()
  await page.waitForURL('**/control/lobby')
  await page.getByRole('button', { name: 'Let’s Play' }).waitFor()
  await page.waitForFunction(() => [...document.querySelectorAll('button')].some(b => b.textContent.includes('Let’s Play') && !b.disabled))
  assert.equal(await page.getByRole('button', { name: 'Let’s Play' }).isEnabled(), true)
  await page.goto(base + '/dashboard')
  await page.getByRole('link', { name: 'Build Game' }).waitFor()
  await page.getByText('Hosted by GIPL042', { exact: false }).waitFor()
  const output = path.join(root, '../test-artifacts/dashboard')
  fs.mkdirSync(output, { recursive: true })
  await page.screenshot({ path: path.join(output, 'desktop.png'), fullPage: true })
  await page.getByRole('link', { name: 'Build Game' }).click()
  await page.getByRole('button', { name: 'Add New Game' }).click()
  await page.getByLabel('Game title').fill('Friday showdown')
  await page.getByRole('button', { name: 'Save game' }).click()
  await page.getByText('Game saved. Choose it from Host Game on your dashboard.').waitFor()
  await page.getByRole('link', { name: 'Dashboard', exact: true }).click()
  await page.getByRole('button', { name: 'Host Game', exact: true }).click()
  await page.getByLabel('Saved game').selectOption({ label: 'Friday showdown' })
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: path.join(output, 'mobile.png'), fullPage: true })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
  await page.getByRole('button', { name: 'Log out' }).click()
  await page.waitForURL('**/login')
  await page.getByLabel('Your user ID').fill('GIPL099')
  await page.getByRole('button', { name: 'Log in', exact: true }).click()
  await page.getByText('Hosted by GIPL042', { exact: false }).waitFor()
  assert.equal(await page.getByRole('link', { name: 'Build Game' }).count(), 0)
  assert.equal(await page.getByRole('button', { name: 'Join Game', exact: true }).isEnabled(), true)
  await page.getByRole('button', { name: 'Join Game', exact: true }).click()
  await page.waitForURL('**/lobby')
  await page.getByText('View players', { exact: false }).click()
  await page.getByRole('heading', { name: 'Who’s in the lobby?' }).waitFor()
  assert.deepEqual(errors, [])
  console.log('Dashboard browser checks passed: login, hosting, saved games, player joining, and mobile layout.')
})().catch(error => { console.error(error); process.exitCode = 1 }).finally(async () => { await browser?.close(); server?.kill() })
